def node_of(graph: dict, node_id: str) -> dict:
    return next(n for n in graph["nodes"] if n["id"] == node_id)


class TestParsing:
    @pytest.mark.parametrize(
        ("formula", "expected"),
        [
            ("='[1]Annual'!B4", ("1", "Annual", "B4", "")),
            ("=[1]Annual!B4", ("1", "Annual", "B4", "")),
            ("='[Budget FY26.xlsx]Q1'!$A$1", ("Budget FY26.xlsx", "Q1", "A1", "")),
            (
                "='C:\\Reports\\[Old.xlsx]Sheet1'!A1",
                ("Old.xlsx", "Sheet1", "A1", "C:\\Reports\\"),
            ),
        ],
    )
    def test_a_reference_is_read_apart(self, formula, expected):
        (ref,) = parse_external_refs(formula)
        assert (ref.book, ref.sheet, ref.cell, ref.directory) == expected

    def test_a_local_formula_names_no_workbook(self):
        assert parse_external_refs("=SUM(A1:A3) + Sheet2!B1") == []

    def test_a_structured_reference_is_not_an_external_one(self):
        """``SalesTable[Revenue]`` brackets a column, not a file."""
        assert parse_external_refs("=SUM(SalesTable[Revenue])") == []

    def test_strings_are_not_references_but_quoted_sheet_names_remain_visible(self):
        assert parse_external_refs('="[1]Data!A1"') == []
        formula = '= "[1]Data!A1" & [1]Data!A1'
        (ref,) = parse_external_refs(formula)
        assert formula[ref.start : ref.end] == "[1]Data!A1"
        assert ref.start == formula.rindex("[1]")
        (quoted,) = parse_external_refs("='[1]Data\"Name'!A1")
        assert quoted.sheet == 'Data"Name'

    def test_substitution_preserves_literal_and_case_insensitive_sheet_collision(self):
        import formualizer as fz

        from linexcel.external import ExternalBook as Reading
        from linexcel.loader import CachedValues
        from linexcel.resolver import _Budget, _ValueResolver

        engine = fz.Workbook()
        engine.add_sheet("S")
        engine.add_sheet("__LINEXCEL_EXTERNAL_1")
        engine.set_value("__LINEXCEL_EXTERNAL_1", 1, 1, 999)
        book = Reading("1", "Ref.xlsx", "Ref.xlsx", cached={("Data", 1, 1): 21})
        resolver = _ValueResolver(
            engine,
            {"S", "__LINEXCEL_EXTERNAL_1"},
            CachedValues({}, set(), False),
            [],
            _Budget(100),
            True,
            externals={"1": book},
        )
        formula = '="[1]Data!A1"&[1]Data!A1'
        rewritten = resolver.substitute_externals(formula)
        assert rewritten.startswith('="[1]Data!A1"&')
        engine.set_formula("S", 1, 1, rewritten)
        assert engine.evaluate_cell("S", 1, 1) == "[1]Data!A121"
        assert engine.get_value("__LINEXCEL_EXTERNAL_1", 1, 1) == 999


class TestDeclaredLinks:
    def test_the_declared_path_is_read_from_the_package(self, declared):
        books = read_external_links(declared)
        assert {b.name for b in books.values()} == {"Budget FY26.xlsx", "Old.xlsx"}
        assert books["1"].target.endswith("Budget FY26.xlsx")

    def test_the_index_is_the_position_in_the_declaration(self, declared):
        """``[2]`` is the second ``<externalReference>``, not a part number."""
        books = read_external_links(declared)
        assert [books[key].name for key in ("1", "2")] == [
            "Budget FY26.xlsx",
            "Old.xlsx",
        ]

    def test_the_sheets_behind_the_link_are_named(self, declared):
        assert read_external_links(declared)["1"].sheets == ["Annual"]

    def test_a_workbook_without_links_declares_none(self):
        assert read_external_links(workbook({"A1": 1})) == {}


class TestNamingWithoutResolving:
    """Without the folder, the answer is *which* file — not silence."""

    def test_the_node_names_the_workbook_it_depends_on(self):
        graph = analyze_workbook(
            workbook({"A1": 2, "B1": "='[Ref.xlsx]Data'!B2 * A1"}), "main.xlsx"
        )["graph"]
        (book,) = node_of(graph, "c:S!B1")["externalBooks"]
        assert book["name"] == "Ref.xlsx"
        assert book["read"] == "none"

    def test_the_grey_node_is_labelled_by_file_rather_than_by_index(self, declared):
        graph = analyze_workbook(declared, "s.xlsx")["graph"]
        labels = {n["label"] for n in graph["nodes"] if n["kind"] == "opaque"}
        assert "[Budget FY26.xlsx]Annual!B4" in labels
        assert "'[1]Annual'!B4" not in labels

    def test_the_warning_names_the_files_and_the_way_out(self):
        graph = analyze_workbook(
            workbook({"A1": 2, "B1": "='[Ref.xlsx]Data'!B2 * A1"}), "main.xlsx"
        )["graph"]
        (warning,) = [w for w in graph["meta"]["warnings"] if "external workbook" in w]
        assert "Ref.xlsx" in warning
        assert "--refs-dir" in warning

    def test_the_stats_count_what_is_read_and_what_is_not(self):
        graph = analyze_workbook(
            workbook({"A1": 2, "B1": "='[Ref.xlsx]Data'!B2 * A1"}), "main.xlsx"
        )["graph"]
        assert graph["meta"]["stats"]["externalWorkbooks"] == 1
        assert graph["meta"]["stats"]["externalWorkbooksRead"] == 0


class TestTheCacheLeftInTheFile:
    """Level 2: no folder, but Excel saved what it last read across the link."""

    def test_the_cached_reading_stands_in_for_the_file(self, declared):
        graph = analyze_workbook(declared, "s.xlsx")["graph"]
        node = node_of(graph, "x:[Budget FY26.xlsx]Annual!B4")
        assert node["value"] == 21
        assert node["valueSource"] == "external-cache"

    def test_the_formula_above_it_is_computed_from_that_reading(self, declared):
        graph = analyze_workbook(declared, "s.xlsx")["graph"]
        assert node_of(graph, "c:S!B1")["value"] == 42

    def test_the_card_says_the_value_is_a_cache_not_a_read(self, declared):
        graph = analyze_workbook(declared, "s.xlsx")["graph"]
        (book,) = node_of(graph, "c:S!B1")["externalBooks"]
        assert book["read"] == "cache"

    def test_a_link_without_a_cache_leaves_the_cell_empty(self, declared):
        graph = analyze_workbook(declared, "s.xlsx")["graph"]
        assert node_of(graph, "c:S!B2")["value"] is None

    def test_a_cache_is_not_counted_as_a_workbook_read(self, declared):
        """It is what Excel saw last time, which may be neither current nor ours."""
        stats = analyze_workbook(declared, "s.xlsx")["graph"]["meta"]["stats"]
        assert stats["externalWorkbooks"] == 2
        assert stats["externalWorkbooksRead"] == 0

    def test_the_warning_separates_the_cached_file_from_the_silent_one(self, declared):
        graph = analyze_workbook(declared, "s.xlsx")["graph"]
        (warning,) = [w for w in graph["meta"]["warnings"] if "external workbook" in w]
        cached, missing = warning.split("Neither read nor cached")
        assert "Budget FY26.xlsx" in cached and "Old.xlsx" not in cached
        assert "Old.xlsx" in missing


class TestResolvingFromAFolder:
    """With the folder, the reference is evaluated as the value it stands for."""

    def test_a_referenced_value_reaches_the_formula_above_it(self, referenced):
        graph = analyze_workbook(
            workbook({"A1": 2, "B1": "='[Ref.xlsx]Data'!B2 * A1"}),
            "main.xlsx",
            refs_dir=referenced,
        )["graph"]
        node = node_of(graph, "c:S!B1")
        assert node["value"] == 42
        assert node["valueSource"] == "external"

    def test_text_crosses_the_link_as_well_as_numbers(self, referenced):
        graph = analyze_workbook(
            workbook({"B1": "='[Ref.xlsx]Data'!B3"}), "main.xlsx", refs_dir=referenced
        )["graph"]
        assert node_of(graph, "c:S!B1")["value"] == "Contoso"

    def test_the_same_cell_without_the_folder_has_no_value(self):
        graph = analyze_workbook(
            workbook({"A1": 2, "B1": "='[Ref.xlsx]Data'!B2 * A1"}), "main.xlsx"
        )["graph"]
        assert node_of(graph, "c:S!B1")["value"] is None

    def test_the_node_says_where_the_file_was_read_from(self, referenced):
        graph = analyze_workbook(
            workbook({"B1": "='[Ref.xlsx]Data'!B2"}), "main.xlsx", refs_dir=referenced
        )["graph"]
        (book,) = node_of(graph, "c:S!B1")["externalBooks"]
        assert book["read"] == "folder"
        assert book["file"].endswith("Ref.xlsx")

    def test_the_grey_node_carries_the_value_it_stands_for(self, referenced):
        graph = analyze_workbook(
            workbook({"B1": "='[Ref.xlsx]Data'!B2"}), "main.xlsx", refs_dir=referenced
        )["graph"]
        node = node_of(graph, "x:[Ref.xlsx]Data!B2")
        assert node["value"] == 21
        assert node["valueSource"] == "external"

    def test_a_missing_file_is_reported_rather_than_guessed(self, tmp_path):
        graph = analyze_workbook(
            workbook({"B1": "='[Nowhere.xlsx]Data'!B2"}),
            "main.xlsx",
            refs_dir=tmp_path,
        )["graph"]
        assert node_of(graph, "c:S!B1")["value"] is None
        (book,) = node_of(graph, "c:S!B1")["externalBooks"]
        assert book["read"] == "none"

    def test_the_public_api_takes_the_folder(self, referenced):
        result = analyze(
            workbook({"B1": "='[Ref.xlsx]Data'!B2"}),
            filename="main.xlsx",
            refs_dir=referenced,
        )
        assert result.stats["externalWorkbooksRead"] == 1

    @pytest.mark.parametrize("targets", [None, ["S!B2"]])
    def test_external_range_and_dependents_keep_all_members_and_provenance(
        self, tmp_path, targets
    ):
        (tmp_path / "Ref.xlsx").write_bytes(
            workbook({"B1": 21, "B2": 10}, sheet="Data")
        )
        result = analyze(
            workbook(
                {
                    "A1": "='[Ref.xlsx]Data'!B1+1",
                    "A2": "=SUM('[Ref.xlsx]Data'!B1:B2)",
                    "B1": "=A1+A2",
                    "B2": "=B1*2",
                }
            ),
            refs_dir=tmp_path,
            targets=targets,
        )
        nodes = {node.get("addr"): node for node in result.nodes}
        for cell, value in {"A1": 22, "A2": 31, "B1": 53, "B2": 106}.items():
            if targets is None and cell in {"B1", "B2"}:
                # The global engine conservatively quarantines uncached
                # dependents. Refusal is preferable to a partial fresh result.
                assert nodes[cell]["value"] is None
                assert nodes[cell].get("valueSource") != "engine"
                continue
            assert nodes[cell]["value"] == value
            # Batch reads the external file's stored values. That is not the
            # indexed engine's fresh evaluation of the external formula closure.
            assert nodes[cell]["valueSource"] == "external"
        assert not any(
            sheet.startswith("__linexcel_external_") for sheet in result.sheets
        )

    def test_external_matrix_preserves_reference_types_and_dimensions(self, tmp_path):
        (tmp_path / "Ref.xlsx").write_bytes(
            workbook(
                {
                    "A1": 10,
                    "B1": "20",
                    "C1": True,
                    "A2": 3,
                    "B2": 4,
                    "C2": 5,
                },
                sheet="Data",
            )
        )
        ref = "'[Ref.xlsx]Data'!A1:C2"
        result = analyze(
            workbook(
                {
                    "A1": f"=SUM({ref})",
                    "A2": f"=COUNT({ref})",
                    "A3": f"=COUNTA({ref})",
                    "A4": f"=ROWS({ref})",
                    "A5": f"=COLUMNS({ref})",
                    "A6": f"=INDEX({ref},1,2)",
                    "A7": f"=INDEX({ref},1,3)",
                    "A8": "=SUM('[Ref.xlsx]Data'!B1)",
                    "A9": "='[Ref.xlsx]Data'!A1+SUM('[Ref.xlsx]Data'!A1:A2)",
                }
            ),
            refs_dir=tmp_path,
        )
        nodes = {node.get("addr"): node for node in result.nodes}
        for cell, expected in {
            "A1": 22,
            "A2": 4,
            "A3": 6,
            "A4": 2,
            "A5": 3,
            "A6": "20",
            "A7": True,
            "A8": 0,
            "A9": 23,
        }.items():
            assert nodes[cell]["value"] == expected

    def test_external_error_and_same_spelling_text_remain_distinct(self, tmp_path):
        book = Workbook()
        book.active.title = "Data"
        book.active["A1"] = "#N/A"
        book.active["A1"].data_type = "s"
        book.active["A2"] = "#N/A"
        book.active["A3"] = 10
        book.save(tmp_path / "Ref.xlsx")
        result = analyze(
            workbook(
                {
                    "A1": "=ISTEXT('[Ref.xlsx]Data'!A1)",
                    "A2": "=ISERROR('[Ref.xlsx]Data'!A1)",
                    "A3": "=ISERROR('[Ref.xlsx]Data'!$A$2)",
                    "A4": "=SUM('[Ref.xlsx]Data'!A2:A3)",
                }
            ),
            refs_dir=tmp_path,
        )
        nodes = {node.get("addr"): node for node in result.nodes}
        assert nodes["A1"]["value"] is True
        assert nodes["A2"]["value"] is False
        assert nodes["A3"]["value"] is True
        assert nodes["A4"]["value"] == "#N/A"

    @pytest.mark.parametrize("range_", ["A1:A2", "A1:A4097"])
    @pytest.mark.parametrize("targets", [None, ["S!C1"]])
    def test_incomplete_external_range_cannot_make_partial_or_guard_result(
        self, tmp_path, range_, targets
    ):
        (tmp_path / "Ref.xlsx").write_bytes(workbook({"A1": 21}, sheet="Data"))
        result = analyze(
            workbook(
                {
                    "A1": f"=IFERROR(SUM('[Ref.xlsx]Data'!{range_}),42)",
                    "B1": "=A1+1",
                    "C1": "=IFERROR(B1,99)",
                }
            ),
            refs_dir=tmp_path,
            targets=targets,
        )
        nodes = {node.get("addr"): node for node in result.nodes}
        for cell in ("A1", "B1", "C1"):
            assert nodes[cell]["value"] is None
            assert nodes[cell].get("valueSource") != "engine"


class TestFolderScanning:
    def test_only_workbooks_are_picked_up(self, tmp_path):
        (tmp_path / "notes.txt").write_text("not a workbook", encoding="utf-8")
        (tmp_path / "Book.xlsx").write_bytes(workbook({"A1": 1}))
        assert set(find_workbooks(tmp_path)) == {"book.xlsx"}

    def test_a_subfolder_is_searched_too(self, tmp_path):
        nested = tmp_path / "add-ins"
        nested.mkdir()
        (nested / "Deep.xlsx").write_bytes(workbook({"A1": 1}))
        assert "deep.xlsx" in find_workbooks(tmp_path)

    def test_macro_files_are_singled_out_for_their_code(self, tmp_path):
        (tmp_path / "Plain.xlsx").write_bytes(workbook({"A1": 1}))
        (tmp_path / "Tools.xlam").write_bytes(
            (Path("tests/fixtures/macros.xlsm")).read_bytes()
        )
        assert [p.name for p in macro_files(tmp_path)] == ["Tools.xlam"]


class TestAddInCode:
    def test_vba_in_the_folder_becomes_part_of_the_lineage(self, tmp_path):
        """Code a workbook calls often lives in an add-in, not in the file."""
        (tmp_path / "Tools.xlam").write_bytes(
            Path("tests/fixtures/macros.xlsm").read_bytes()
        )
        graph = analyze_workbook(workbook({"A1": 1}), "main.xlsx", refs_dir=tmp_path)[
            "graph"
        ]
        vba = [n for n in graph["nodes"] if n["kind"] == "vba"]
        assert vba, "the add-in's procedures should be nodes"
        assert all("Tools.xlam:" in n["module"] for n in vba)

    def test_nothing_is_read_from_disk_without_the_folder(self, tmp_path):
        (tmp_path / "Tools.xlam").write_bytes(
            Path("tests/fixtures/macros.xlsm").read_bytes()
        )
        graph = analyze_workbook(workbook({"A1": 1}), "main.xlsx")["graph"]
        assert not [n for n in graph["nodes"] if n["kind"] == "vba"]
